"""Generate enum/constants only; keep validation behavior in the hand-written DTOs."""

import argparse
import hashlib
import json
from pathlib import Path

import yaml


ROOT = Path(__file__).resolve().parents[1]
ENUM_PATHS = {
    "ModelLifecycle": "modelLifecycle",
    "ObservationEvaluation": "observationEvaluation",
    "WarningLifecycle": "warningLifecycle",
    "ValidationLevel": "validationLevel",
    "ObservationQuality": "observationQuality",
    "ModeId": "modeIds",
    "SignalKey": "observationSchema.signalKeys",
    "DerivedSignalKey": "trendContract.derivedSignals",
    "Source": "trendContract.sourceValues",
    "Resolution": "trendContract.resolutions",
    "Severity": "observability.severities",
    "Component": "observability.components",
    "Outcome": "observability.outcomes",
    "EventName": "observability.eventNames",
    "PresentationState": "advisoryManagement.presentationState",
    "CaptureState": "evidencePacket.captureStates",
}
CONSTANT_PATHS = {
    "VERSION": "contractVersion",
    "INITIAL_DEVICE": "initialDevice",
    "MAX_POINTS_PER_SERIES": "trendContract.maxPointsPerSeries",
    "THIN_DEMO_QUERY_MAX_SECONDS": "trendContract.thinDemoQueryMaxSeconds",
    "THIN_DEMO_MAX_SIGNALS": "trendContract.thinDemoMaxSignals",
    "OBSERVATION_REQUIRED_FIELDS": "observationSchema.required",
    "DEVICE_HEALTH_REQUIRED_FIELDS": "modelOutput.required",
    "EVENT_REQUIRED_FIELDS": "observability.eventRequiredFields",
    "EVENT_OPTIONAL_FIELDS": "observability.eventOptionalFields",
    "TREND_RESPONSE_REQUIRED_FIELDS": "trendContract.trendResponseRequiredFields",
    "API_ERROR_REQUIRED_FIELDS": "apiErrorRequiredFields",
    "NO_SENSITIVE_FIELDS": "observability.noSensitiveFields",
    "API_ROUTES_THIN_DEMO": "apiRoutesThinDemo",
}


def at(contract, path):
    value = contract
    for part in path.split("."):
        value = value[part]
    return value


def enums(contract):
    result = {name: list(at(contract, path)) for name, path in ENUM_PATHS.items()}
    result["EventName"] = list(dict.fromkeys(result["EventName"] + contract["advisoryManagement"]["newEventNames"]))
    return result


def render(contract):
    digest = hashlib.sha256(json.dumps(contract, sort_keys=True, ensure_ascii=False).encode()).hexdigest()
    py = ["# Generated by scripts/generate_contracts.py; do not edit.", "from enum import StrEnum", "", f'CONTRACT_SHA256 = "{digest}"']
    cs = ["// Generated by scripts/generate_contracts.py; do not edit.", "using System.Text.Json.Serialization;", "", "namespace Aegis.Contracts;", "", "public static class Contract", "{", f'    public const string Sha256 = "{digest}";']
    for name, path in CONSTANT_PATHS.items():
        value = at(contract, path)
        py.append(f"{name} = {tuple(value) if isinstance(value, list) else value!r}")
        cs_name = "".join(word.title() for word in name.split("_"))
        if isinstance(value, list):
            cs.append(f"    public static readonly string[] {cs_name} = [{', '.join(json.dumps(x) for x in value)}];")
        else:
            cs.append(f"    public const {'int' if isinstance(value, int) else 'string'} {cs_name} = {json.dumps(value)};")
    cs.extend(["}", ""])
    for name, values in enums(contract).items():
        py.extend(["", "", f"class {name}(StrEnum):"])
        cs.extend([f"public enum {name}", "{"])
        for value in values:
            member = {"1m": "Minute", "1h": "Hour"}.get(value, value)
            py.append(f"    {member} = {value!r}")
            if member != value:
                cs.append(f"    [JsonStringEnumMemberName({json.dumps(value)})]")
            cs.append(f"    {member},")
        cs.extend(["}", ""])
    return {"src/aegis/contracts_generated.py": "\n".join(py) + "\n", "src/Aegis.Contracts/Contract.g.cs": "\n".join(cs)}


def check(root, contract):
    return [path for path, text in render(contract).items()
            if not (root / path).exists() or (root / path).read_text(encoding="utf-8") != text]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    contract = yaml.safe_load((ROOT / "AEGIS_CONTRACT_v3_4.yaml").read_text(encoding="utf-8"))
    if args.check:
        changed = check(ROOT, contract)
        if changed:
            raise SystemExit("Contract drift: " + ", ".join(changed))
        print("PASS: generated Python/C# contracts match YAML")
        return
    for path, text in render(contract).items():
        output = ROOT / path
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text, encoding="utf-8", newline="\n")
    print("Generated Python/C# enum and constants")


if __name__ == "__main__":
    main()
